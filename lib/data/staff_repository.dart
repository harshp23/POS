  const StaffLogin({
    required this.userId,
    required this.fullName,
    required this.email,
    this.phoneNumber = '',
    required this.posRole,
    this.posRoleName = '',
    this.roleId,
    this.roleName,
    this.status = 'Active',
    this.staffId,
    this.staffName,
    this.staffCode,
    this.deliveryEnabled = false,
    this.lastLoginAt,
    this.lastSeenAt,
