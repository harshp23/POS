class StaffMember {
  const StaffMember({
    this.id = '',
    this.staffCode = '',
    required this.fullName,
    this.mobile = '',
    this.email = '',
    this.emergencyContact = '',
    this.designation = '',
    this.department = '',
    this.bankName = '',
    this.accountNumber = '',
    this.ifsc = '',
    this.upiId = '',
    this.photoUrl = '',
    this.idProofUrl = '',
    this.address = '',
    this.joiningDate,
    this.salaryType = 'monthly',
    this.monthlySalary = 0,
    this.dailyWage = 0,
    this.hourlyRate = 0,
    this.workingHours = 8,
    this.compensationModel = 'salary_incentive',
    this.incentiveType = 'sales_target',
    this.incentiveValue = 0,
    this.status = 'active',
    this.locationId,
    this.locationName,
    this.deliveryEnabled = false,
    this.userId,
    this.roleId,
    this.roleName,
    this.loginEmail,
    this.loginStatus,
  });

  final String id;

  /// Short code shown on the POS (e.g. VIN-042), generated by the server.
  final String staffCode;
  final String fullName;
  final String mobile;
  final String email;
  final String emergencyContact;

  /// Free-text job title (Captain, Biller, Chef…).
  final String designation;
  final String department;
  final String bankName;
  final String accountNumber;
  final String ifsc;
  final String upiId;
  final String photoUrl;
  final String idProofUrl;
  final String address;

  /// YYYY-MM-DD.
  final String? joiningDate;

  /// monthly | daily | hourly.
  final String salaryType;
  final double monthlySalary;
  final double dailyWage;
  final double hourlyRate;
  final double workingHours;

  /// salary_only | salary_incentive.
  final String compensationModel;

  /// sales_target | fixed_amount | percentage.
  final String incentiveType;
  final double incentiveValue;

  /// active | inactive.
  final String status;

  /// The branch this person works at; null = the whole restaurant.
  final String? locationId;

  /// The branch's name as the server sent it (read-only; not saved).
  final String? locationName;
  final bool deliveryEnabled;

  /// The app login linked to this employee (users.id), if any.
  final String? userId;
  final String? roleId;
  final String? roleName;
  final String? loginEmail;
  final String? loginStatus;

  bool get isActive => status == 'active';
  bool get hasLogin => userId != null;

  /// Salary shown in the directory, by salary type.
  double get payRate => switch (salaryType) {
        'daily' => dailyWage,
        'hourly' => hourlyRate,
        _ => monthlySalary,
      };

  String get initials {
    final parts = fullName.trim().split(RegExp(r'\s+'));
    if (parts.isEmpty || parts.first.isEmpty) return '?';
    if (parts.length == 1) {
      return parts.first
          .substring(0, parts.first.length.clamp(1, 2))
          .toUpperCase();
    }
    return (parts.first[0] + parts[1][0]).toUpperCase();
  }

  factory StaffMember.fromJson(Map<String, dynamic> j) {
    final login =
        j['login'] is Map ? (j['login'] as Map).cast<String, dynamic>() : null;
    return StaffMember(
      id: '${j['id']}',
      staffCode: _s(j['staff_code'], ''),
      fullName: _s(j['full_name'], ''),
      mobile: _s(j['mobile'], ''),
      email: _s(j['email'], ''),
      emergencyContact: _s(j['emergency_contact'], ''),
      designation: _s(j['designation'], ''),
      department: _s(j['department'], ''),
      bankName: _s(j['bank_name'], ''),
      accountNumber: _s(j['account_number'], ''),
      ifsc: _s(j['ifsc'], ''),
      upiId: _s(j['upi_id'], ''),
      photoUrl: _s(j['photo_url'], ''),
      idProofUrl: _s(j['id_proof_url'], ''),
      address: _s(j['address'], ''),
      joiningDate: _str(j['joining_date']),
      salaryType: _s(j['salary_type'], 'monthly'),
      monthlySalary: _num(j['monthly_salary']),
      dailyWage: _num(j['daily_wage']),
      hourlyRate: _num(j['hourly_rate']),
      workingHours: _num(j['working_hours'], 8),
      compensationModel: _s(j['compensation_model'], 'salary_only'),
      incentiveType: _s(j['incentive_type'], 'sales_target'),
      incentiveValue: _num(j['incentive_value']),
      status: _s(j['status'], 'active'),
      locationId: _str(j['location_id']),
      locationName: _text(j['location_name']),
      deliveryEnabled: j['delivery_enabled'] == true,
      userId: _str(j['user_id']),
      roleId: _str(j['role_id']),
      roleName: _str(j['role_name']),
      loginEmail: _str(login?['email']),
      loginStatus: _str(login?['status']),
    );
  }

  /// The editable fields, as the API takes them.
  Map<String, Object?> toJson() => {
        'full_name': fullName,
        'mobile': mobile,
        'email': email,
        'emergency_contact': emergencyContact,
        'designation': designation,
        'department': department,
        'bank_name': bankName,
        'account_number': accountNumber,
        'ifsc': ifsc,
        'upi_id': upiId,
        'photo_url': photoUrl,
        'id_proof_url': idProofUrl,
        'address': address,
        'joining_date': joiningDate,
        'salary_type': salaryType,
        'monthly_salary': monthlySalary,
        'daily_wage': dailyWage,
        'hourly_rate': hourlyRate,
        'working_hours': workingHours,
        'compensation_model': compensationModel,
        'incentive_type': incentiveType,
        'incentive_value': incentiveValue,
        'status': status,
        'location_id': locationId,
        'delivery_enabled': deliveryEnabled,
      };

  StaffMember copyWith({
    String? id,
    String? staffCode,
    String? fullName,
    String? status,
    bool? deliveryEnabled,
    String? userId,
    String? roleId,
    String? roleName,
    String? loginEmail,
    String? loginStatus,
  }) =>
      StaffMember(
        id: id ?? this.id,
        staffCode: staffCode ?? this.staffCode,
        fullName: fullName ?? this.fullName,
        mobile: mobile,
        email: email,
        emergencyContact: emergencyContact,
        designation: designation,
        department: department,
        bankName: bankName,
        accountNumber: accountNumber,
        ifsc: ifsc,
        upiId: upiId,
        photoUrl: photoUrl,
        idProofUrl: idProofUrl,
        address: address,
        joiningDate: joiningDate,
        salaryType: salaryType,
        monthlySalary: monthlySalary,
        dailyWage: dailyWage,
        hourlyRate: hourlyRate,
        workingHours: workingHours,
        compensationModel: compensationModel,
        incentiveType: incentiveType,
        incentiveValue: incentiveValue,
        status: status ?? this.status,
        locationId: locationId,
        locationName: locationName,
        deliveryEnabled: deliveryEnabled ?? this.deliveryEnabled,
        userId: userId ?? this.userId,
        roleId: roleId ?? this.roleId,
        roleName: roleName ?? this.roleName,
        loginEmail: loginEmail ?? this.loginEmail,
        loginStatus: loginStatus ?? this.loginStatus,
      );
}

