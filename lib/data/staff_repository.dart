/// Staff & Users (vendor panel): employees, logins and roles, attendance,
/// shifts, advances, salaries, approvals, audit log, reports and training.
///
/// [ApiStaffRepository] talks to the Proviyaa backend (`/v1/staff/*`);
/// [InMemoryStaffRepository] (staff_repository_memory.dart) backs the local
/// demo mode and widget tests. Money is in rupees; dates are `YYYY-MM-DD`.

String isoDate(DateTime d) =>
    '${d.year.toString().padLeft(4, '0')}-${d.month.toString().padLeft(2, '0')}-${d.day.toString().padLeft(2, '0')}';

double _num(Object? v, [double fallback = 0]) => v == null
    ? fallback
    : (v is num ? v.toDouble() : double.tryParse('$v') ?? fallback);
int _int(Object? v, [int fallback = 0]) => v == null
    ? fallback
    : (v is num ? v.toInt() : int.tryParse('$v') ?? fallback);
String? _str(Object? v) => v == null ? null : '$v';

/// A text field that may be missing (or not a string) on the wire.
String _s(Object? v, [String fallback = '']) =>
    v == null ? fallback : (v is String ? v : '$v');

/// A non-empty text field, else null.
String? _text(Object? v) {
  final s = v == null ? '' : '$v'.trim();
  return s.isEmpty ? null : s;
}

/// A JSON object field (the server may also send it as a JSON string).
Map<String, dynamic> _obj(Object? v) {
  if (v is Map) return v.cast<String, dynamic>();
  if (v is String && v.trim().startsWith('{')) {
    try {
      final d = jsonDecode(v);
      if (d is Map) return d.cast<String, dynamic>();
    } catch (_) {}
  }
  return const {};
}

/// The human name of a built-in role — never its key (`org_admin`).
String posRoleLabel(String? key) => PosRoles.names[key] ?? 'No role';
DateTime? _time(Object? v) => v == null ? null : DateTime.tryParse('$v');
List<Map<String, dynamic>> _list(Object? v) => [
      for (final e in (v as List? ?? const []))
        (e as Map).cast<String, dynamic>(),
    ];

