/// A report as a table, for CSV export or printing.
class ReportTable {
  const ReportTable({
    required this.kind,
    required this.title,
    required this.columns,
    required this.rows,
  });
  final String kind;
  final String title;
  final List<String> columns;
  final List<List<String>> rows;

  factory ReportTable.fromJson(Map<String, dynamic> j) => ReportTable(
        kind: '${j['kind']}',
        title: _s(j['title'], ''),
        columns: [for (final c in (j['columns'] as List? ?? const [])) '$c'],
        rows: [
          for (final r in (j['rows'] as List? ?? const []))
            [for (final c in (r as List)) c == null ? '' : '$c'],
        ],
      );

  String toCsv() {
    String cell(String v) =>
        RegExp(r'[",\n]').hasMatch(v) ? '"${v.replaceAll('"', '""')}"' : v;
    return [
      columns.map(cell).join(','),
      for (final r in rows) r.map(cell).join(','),
    ].join('\n');
  }
}

