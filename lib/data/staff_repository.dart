  Future<TrainingOverview> training() async =>
      TrainingOverview.fromJson(await _map(api.get('v1/staff/training')));

  @override
  Future<TrainingModule> saveTrainingModule(TrainingModule module) async =>
      TrainingModule.fromJson(await _map(module.id.isEmpty
          ? api.post('v1/staff/training', module.toJson())
          : api.patch('v1/staff/training/${module.id}', module.toJson())));

  @override
  Future<void> deleteTrainingModule(String id) async =>
      api.delete('v1/staff/training/$id');

  @override
  Future<TrainingResult> submitTrainingAttempt(
          String moduleId, String staffId, List<int> answers) async =>
      TrainingResult.fromJson(await _map(api.post(
          'v1/staff/training/$moduleId/attempts',
          {'staff_id': staffId, 'answers': answers})));
}
