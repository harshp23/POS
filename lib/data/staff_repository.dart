    this.locationId,
    this.locationName,
  });

  final String userId;
  final String fullName;
  final String email;
  final String phoneNumber;

  /// Built-in role the login works with on the server (users.pos_role).
  final String posRole;

  /// Its human name (Branch Manager, Cashier…) — never the key.
  final String posRoleName;

  /// Staff role (custom or seeded) that decides the screens.
  final String? roleId;
  final String? roleName;

  /// Active | Inactive | Suspended.
  final String status;
  final String? staffId;
  final String? staffName;
  final String? staffCode;
  final bool deliveryEnabled;
  final DateTime? lastLoginAt;
  final DateTime? lastSeenAt;
  final int failedAttempts;
  final bool forcePasswordChange;
  final bool twoFactorEnabled;
  final DateTime? lockedUntil;

  /// The restaurant owner — the panel doesn't let others change them.
  final bool isOwner;

  /// The login's home branch (users.location_id); null = every branch.
  final String? locationId;

  /// The home branch's name as the server sent it.
  final String? locationName;

  bool get isActive => status.toLowerCase() == 'active';
  String get displayRole => roleName ?? posRoleName;

  factory StaffLogin.fromJson(Map<String, dynamic> j) => StaffLogin(
        userId: '${j['user_id']}',
        fullName: _s(j['full_name'], ''),
        email: _s(j['email'], ''),
        phoneNumber: _s(j['phone_number'], ''),
        posRole: _s(j['pos_role'], 'none'),
        posRoleName: _text(j['pos_role_name']) ??
            posRoleLabel(_str(j['pos_role'])),
        locationId: _str(j['location_id']),
        locationName: _text(j['location_name']),
        roleId: _str(j['role_id']),
        roleName: _str(j['role_name']),
        status: _s(j['status'], 'Active'),
        staffId: _str(j['staff_id']),
        staffName: _str(j['staff_name']),
        staffCode: _str(j['staff_code']),
        deliveryEnabled: j['delivery_enabled'] == true,
        lastLoginAt: _time(j['last_login_at']),
        lastSeenAt: _time(j['last_seen_at']),
        failedAttempts: _int(j['failed_attempts']),
        forcePasswordChange: j['force_password_change'] == true,
        twoFactorEnabled: j['two_factor_enabled'] == true,
        lockedUntil: _time(j['locked_until']),
        isOwner: j['pos_role'] == 'org_owner',
      );
}

