-- ----------------------------------------------------------------------------
-- Accounts are master-admin's public.users (not Supabase Auth): point every
-- pos_* user column there, also on tables made by an earlier run of this
-- file that referenced auth.users.
-- ----------------------------------------------------------------------------
do $$
declare r record;
begin
  for r in
    select c.conrelid::regclass as tbl, c.conname, a.attname as col
      from pg_constraint c
      join pg_attribute a on a.attrelid = c.conrelid and a.attnum = c.conkey[1]
     where c.contype = 'f'
       and c.confrelid = 'auth.users'::regclass
       and c.conrelid::regclass::text like 'pos\_%'
  loop
    execute format('alter table %s drop constraint %I', r.tbl, r.conname);
    execute format('alter table %s add constraint %I foreign key (%I) references public.users (id) on delete set null',
                   r.tbl, r.conname, r.col);
  end loop;
end;
$$;
