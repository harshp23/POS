-- The same four-policy shape as the OS's apply_org_rls() (0010), plus an
-- optional member DELETE, created only where missing so re-runs are no-ops.
create or replace function public.pos_apply_member_rls(tbl regclass, allow_delete boolean)
returns void
language plpgsql
set search_path = public, pg_temp
as $$
declare
  t text := tbl::text;
  n text := (select relname from pg_class where oid = tbl);
begin
  execute format('alter table %s enable row level security', t);
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = n and policyname = n || '_platform_admin_all') then
    execute format('create policy %I on %s for all using (public.is_platform_admin()) with check (public.is_platform_admin())', n || '_platform_admin_all', t);
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = n and policyname = n || '_member_select') then
    execute format('create policy %I on %s for select using (organization_id = public.current_org_id())', n || '_member_select', t);
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = n and policyname = n || '_member_insert') then
    execute format('create policy %I on %s for insert with check (organization_id = public.current_org_id())', n || '_member_insert', t);
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = n and policyname = n || '_member_update') then
    execute format('create policy %I on %s for update using (organization_id = public.current_org_id()) with check (organization_id = public.current_org_id())', n || '_member_update', t);
  end if;
  if allow_delete and not exists (select 1 from pg_policies where schemaname = 'public' and tablename = n and policyname = n || '_member_delete') then
    execute format('create policy %I on %s for delete using (organization_id = public.current_org_id())', n || '_member_delete', t);
  end if;
  execute format('revoke all on %s from anon', t);
  if allow_delete then
    execute format('grant select, insert, update, delete on %s to authenticated', t);
  else
    execute format('grant select, insert, update on %s to authenticated', t);
  end if;
  execute format('grant all privileges on %s to service_role', t);
end;
$$;

